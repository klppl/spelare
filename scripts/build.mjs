// Builds the content scripts in extension/ from src/.
//
//   node scripts/build.mjs          write extension/mac.js and extension/observer.js
//   node scripts/build.mjs --check  exit 1 if either is stale
//
// Each content script has an entry module in src/content/; esbuild bundles it
// and the modules it imports into one IIFE (Safari content scripts can't be
// ES modules). Each __SPELARE_PAGE_SCRIPT__("<name>") call in a bundle is
// then replaced by a string literal holding the page-world script of that
// name, which the content script injects as an inline <script>.

import fs from 'node:fs';
import path from 'node:path';
import { parse } from 'acorn';
import { buildSync } from 'esbuild';
import { ROOT, CONTENT_SCRIPTS } from './lib/mac-source.mjs';

const CONTENT_DIR = path.join(ROOT, 'src/content');
const PAGE_DIR = path.join(ROOT, 'src/page');
const PLACEHOLDER = '__SPELARE_PAGE_SCRIPT__';

const HEADER = '// Generated by scripts/build.mjs from src/ (npm run build). Do not edit.\n';

// Page-world scripts, each the concatenation of its parts. A string part is
// copied as-is; { module } is an ES module bundled into a strict-mode IIFE.
export const PAGE_SCRIPTS = {
    'caption-mirroring': ['caption-mirroring.js'],
    // The vendored yt-dlp/ejs solver must run first: the observer calls
    // the window.__tubelessJSC it defines.
    'stream-observer': ['vendor/yt-dlp-ejs.js', { module: 'stream-observer.js' }],
    'player-bridge': [{ module: 'player-bridge.js' }],
};

export function pageScript(name) {
    const parts = PAGE_SCRIPTS[name];
    if (!parts) throw new Error(`Unknown page script "${name}" (known: ${Object.keys(PAGE_SCRIPTS).join(', ')})`);
    return parts
        .map((part) => (typeof part === 'string'
            ? fs.readFileSync(path.join(PAGE_DIR, part), 'utf8')
            : bundle(path.join(PAGE_DIR, part.module), { strict: true })))
        .join('');
}

// Replaces every placeholder call in `source` using `literalFor(name)`.
export function substitutePageScripts(source, literalFor) {
    const calls = [];
    (function walk(node) {
        if (!node || typeof node !== 'object') return;
        if (node.type === 'CallExpression' && node.callee.type === 'Identifier' && node.callee.name === PLACEHOLDER) {
            const [arg] = node.arguments;
            if (node.arguments.length !== 1 || arg.type !== 'Literal' || typeof arg.value !== 'string') {
                throw new Error(`${PLACEHOLDER}() takes one string literal (offset ${node.start})`);
            }
            calls.push({ start: node.start, end: node.end, name: arg.value });
            return;
        }
        for (const key in node) walk(node[key]);
    })(parse(source, { ecmaVersion: 'latest' }));

    let output = source;
    for (const call of calls.sort((a, b) => b.start - a.start)) {
        output = output.slice(0, call.start) + literalFor(call.name) + output.slice(call.end);
    }
    return { output, names: calls.map((call) => call.name) };
}

// Bundles an ES module and its imports into one unminified IIFE, so the
// output stays readable. ES modules are strict but esbuild's IIFE output
// isn't, so { strict: true } puts the directive back inside the IIFE.
function bundle(entryPoint, { strict = false } = {}) {
    const result = buildSync({
        entryPoints: [entryPoint],
        bundle: true,
        format: 'iife',
        write: false,
        charset: 'utf8',
        legalComments: 'inline',
        logLevel: 'silent',
    });
    const code = result.outputFiles[0].text;
    if (!strict) return code;
    if (!code.startsWith('(() => {\n')) throw new Error(`Unexpected bundle prologue in ${entryPoint}`);
    return code.replace('(() => {\n', '(() => {\n  "use strict";\n');
}

export function bundleContentScript(file) {
    return bundle(path.join(CONTENT_DIR, file));
}

// The built content scripts, keyed by file name in extension/. Every page
// script is injected by exactly one of them.
export function buildContentScripts() {
    const built = {};
    const injectedBy = {};
    for (const file of Object.keys(CONTENT_SCRIPTS)) {
        const { output, names } = substitutePageScripts(bundleContentScript(file), (name) => JSON.stringify(pageScript(name)));
        for (const name of names) {
            if (injectedBy[name]) throw new Error(`Page script "${name}" is injected by both ${injectedBy[name]} and ${file}`);
            injectedBy[name] = file;
        }
        built[file] = HEADER + output;
    }
    const unused = Object.keys(PAGE_SCRIPTS).filter((name) => !injectedBy[name]);
    if (unused.length) throw new Error(`Page scripts never injected by src/content/: ${unused.join(', ')}`);
    return built;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const stale = [];
    for (const [file, built] of Object.entries(buildContentScripts())) {
        const target = CONTENT_SCRIPTS[file];
        const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
        if (current === built) {
            console.log(`extension/${file} ${process.argv.includes('--check') ? 'is up to date' : 'unchanged'}`);
        } else if (process.argv.includes('--check')) {
            stale.push(file);
        } else {
            fs.writeFileSync(target, built);
            console.log(`wrote extension/${file} (${built.length} bytes)`);
        }
    }
    if (stale.length) {
        console.error(`${stale.map((file) => `extension/${file}`).join(', ')} out of date with src/. Run: npm run build`);
        process.exit(1);
    }
}
